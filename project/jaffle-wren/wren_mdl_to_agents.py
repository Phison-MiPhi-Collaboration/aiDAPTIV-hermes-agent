#!/usr/bin/env python3
"""Write a compact, byte-stable summary of a Wren project's MDL into its AGENTS.md.

Hermes loads AGENTS.md from the folder it is started in into the cached (static) part of
its system prompt. Putting the schema there lets aiDAPTIV+ serve it from SSD in every new
session, so the model can go straight to `wren --sql` instead of spending tool calls on
`wren memory fetch` / `wren context show`.

The summary sits between two marker lines and is replaced in place on every run; the rest
of AGENTS.md is left untouched. The output depends only on target/mdl.json (and, unless
--no-rules, knowledge/rules/*.md): no timestamps, fixed ordering. When nothing changed the
file is not rewritten, so the cached prefix stays valid.

Usage (run from the Wren project folder, e.g. wren-jaffle):
    wren context build                      # refresh target/mdl.json first
    python wren_mdl_to_agents.py            # update AGENTS.md
    python wren_mdl_to_agents.py --dry-run  # print the block only
    python wren_mdl_to_agents.py --check    # exit 1 if AGENTS.md is out of date

After AGENTS.md changes, start one Hermes session FROM THIS FOLDER and ask a throwaway
question, so the new prefix is written to SSD (warm-up). Do not use `hermes -q` for that.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

BEGIN = "<!-- BEGIN WREN MDL SUMMARY: generated by wren_mdl_to_agents.py from target/mdl.json; do not edit by hand -->"
END = "<!-- END WREN MDL SUMMARY -->"


def _one_line(text: object) -> str:
    """Collapse whitespace so every entry stays on one line."""
    return " ".join(str(text or "").split())


def _description(obj: dict) -> str:
    """First line of the description; longer descriptions go through _description_rest."""
    return _one_line(str((obj.get("properties") or {}).get("description") or "").strip().split("\n")[0])


def _description_rest(obj: dict, indent: str) -> list[str]:
    """Lines 2+ of a multi-line description (e.g. a markdown table of enum values), indented
    under their bullet, with table padding squeezed out so it costs fewer tokens."""
    lines = str((obj.get("properties") or {}).get("description") or "").strip().split("\n")[1:]
    out = []
    for line in lines:
        line = _one_line(line)
        if not line:
            continue
        if set(line) <= set("|-: "):  # table separator row such as |-----|------|
            line = "|" + "|".join("---" for _ in range(line.count("|") - 1)) + "|"
        else:
            line = " | ".join(cell.strip() for cell in line.split("|")).strip()
        out.append(indent + line)
    return out


def _column_line(col: dict, primary_key: str | None, with_descriptions: bool) -> list[str]:
    notes = []
    if col.get("isPrimaryKey") or col.get("name") == primary_key:
        notes.append("PK")
    if col.get("notNull"):
        notes.append("not null")
    if col.get("relationship"):
        notes.append(f"relationship {col['relationship']}")
    if col.get("isCalculated"):
        notes.append(f"calculated: {_one_line(col.get('expression'))}")
    head = f"- {col['name']} ({', '.join([col.get('type') or '?', *notes])})"
    if not with_descriptions:
        return [head]
    desc = _description(col)
    return [f"{head}: {desc}" if desc else head, *_description_rest(col, "  ")]


def _model_section(model: dict, with_descriptions: bool) -> list[str]:
    lines = [f"### {model['name']}"]
    desc = _description(model) if with_descriptions else ""
    if desc:
        lines.append(desc)
    if model.get("primaryKey"):
        lines.append(f"Primary key: {model['primaryKey']}")
    for col in model.get("columns") or []:
        lines += _column_line(col, model.get("primaryKey"), with_descriptions)
    return lines


def _relationship_line(rel: dict) -> str:
    models = " → ".join(rel.get("models") or [])
    cond = _one_line(rel.get("condition"))
    return f"- {rel['name']}: {models} ({rel.get('joinType', '?')})" + (f" ON {cond}" if cond else "")


def _named_items(items: object) -> str:
    """Names of a cube's measures/dimensions, whatever shape the list has."""
    if not isinstance(items, list):
        return ""
    return ", ".join(str(i.get("name")) if isinstance(i, dict) else str(i) for i in items)


def _cube_lines(cube: dict) -> list[str]:
    lines = [f"- {cube.get('name')}" + (f" (base model {cube['baseObject']})" if cube.get("baseObject") else "")]
    for key in ("measures", "dimensions", "timeDimensions"):
        names = _named_items(cube.get(key))
        if names:
            lines.append(f"  - {key}: {names}")
    return lines


def _demote_headings(markdown: str, levels: int = 3) -> list[str]:
    """Nest a rules file under our section: '# X' -> '#### X', leaving code fences alone."""
    out, in_fence = [], False
    for line in markdown.splitlines():
        if line.lstrip().startswith("```"):
            in_fence = not in_fence
        if not in_fence and line.startswith("#"):
            hashes = len(line) - len(line.lstrip("#"))
            line = "#" * min(6, hashes + levels) + line[hashes:]
        out.append(line.rstrip())
    return out


def build_block(project: Path, with_rules: bool, with_descriptions: bool, wren_cmd: str = "wren") -> str:
    mdl = json.loads((project / "target" / "mdl.json").read_text(encoding="utf-8"))
    rules_files = sorted((project / "knowledge" / "rules").glob("*.md")) if with_rules else []

    lines = [
        BEGIN,
        "## Data model (Wren MDL), already loaded",
        "",
        "Answer every data question through Wren: write SQL against the model names below and run "
        f'`{wren_cmd} --sql "<SQL>"` from this folder. Do not search for or open database files '
        "(.duckdb, .db, .csv) and do not query the database with Python, duckdb or other clients: "
        "Wren applies the semantic layer and the business rules.",
        "",
        f"Data source: {mdl.get('dataSource', '?')}. Use the model names below, not raw database tables.",
        "This schema is current. Do not run `wren memory fetch`, `wren context show` or read "
        "`target/mdl.json` to look up models or columns: they are all listed here. "
        + ("The business rules are included below, so `wren context instructions` is not needed. "
           if rules_files else "")
        + "`wren memory recall` for similar past queries is still useful.",
        "",
        "Column format: name (type, flags): description.",
    ]
    for model in sorted(mdl.get("models") or [], key=lambda m: m["name"]):
        lines += ["", *_model_section(model, with_descriptions)]

    relationships = sorted(mdl.get("relationships") or [], key=lambda r: r["name"])
    if relationships:
        lines += ["", "### Relationships", *(_relationship_line(r) for r in relationships)]

    views = sorted(mdl.get("views") or [], key=lambda v: v["name"])
    if views:
        lines += ["", "### Views"]
        lines += [f"- {v['name']}: {_one_line(v.get('statement'))}" for v in views]

    cubes = sorted(mdl.get("cubes") or [], key=lambda c: str(c.get("name")))
    if cubes:
        lines += ["", "### Cubes (query with `wren cube query`)"]
        for cube in cubes:
            lines += _cube_lines(cube)

    if rules_files:
        lines += ["", "### Business rules (from knowledge/rules)"]
        for path in rules_files:
            lines += ["", *_demote_headings(path.read_text(encoding="utf-8").strip())]

    lines.append(END)
    return "\n".join(lines)


def merge(existing: str, block: str) -> str:
    """Replace the marked block, or append it; existing text outside the markers is kept."""
    start, end = existing.find(BEGIN), existing.find(END)
    if start != -1 and end != -1 and end > start:
        return existing[:start] + block + existing[end + len(END):]
    if start != -1 or end != -1:
        raise SystemExit("AGENTS.md has only one of the two marker lines; fix it by hand first.")
    sep = "" if not existing else ("\n" if existing.endswith("\n\n") else "\n\n" if existing.endswith("\n") else "\n\n\n")
    return existing + sep + block + "\n"


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--project", type=Path, default=Path("."), help="Wren project folder (default: current folder)")
    ap.add_argument("--agents", type=Path, help="AGENTS.md to update (default: <project>/AGENTS.md)")
    ap.add_argument("--no-rules", action="store_true", help="leave out knowledge/rules/*.md")
    ap.add_argument("--no-descriptions", action="store_true", help="leave out model and column descriptions")
    ap.add_argument("--wren-cmd", default="wren",
                    help="how the agent should call wren, e.g. the full path to wren.exe when it is not on PATH")
    ap.add_argument("--dry-run", action="store_true", help="print the block, write nothing")
    ap.add_argument("--check", action="store_true", help="exit 1 if AGENTS.md is out of date, write nothing")
    args = ap.parse_args()

    project = args.project.resolve()
    if not (project / "target" / "mdl.json").is_file():
        print(f"error: {project / 'target' / 'mdl.json'} not found; run `wren context build` first", file=sys.stderr)
        return 2
    agents = (args.agents or project / "AGENTS.md").resolve()

    block = build_block(project, with_rules=not args.no_rules, with_descriptions=not args.no_descriptions,
                        wren_cmd=args.wren_cmd)
    if args.dry_run:
        print(block)
        print(f"\n[{len(block)} chars, about {len(block) // 4} tokens]", file=sys.stderr)
        return 0

    raw = agents.read_bytes().decode("utf-8") if agents.exists() else ""
    crlf = "\r\n" in raw
    existing = raw.replace("\r\n", "\n")
    updated = merge(existing, block)
    if crlf:  # keep the file's own line endings so unrelated bytes never change
        updated = updated.replace("\n", "\r\n")

    if updated == raw:
        print(f"unchanged: {agents} (cached prefix still valid, no warm-up needed)")
        return 0
    if args.check:
        print(f"out of date: {agents} (rerun without --check)")
        return 1
    agents.write_bytes(updated.encode("utf-8"))
    print(f"updated: {agents} (block {len(block)} chars, about {len(block) // 4} tokens)")
    print("next: start Hermes from this folder and ask one throwaway question to warm the SSD cache")
    return 0


if __name__ == "__main__":
    sys.exit(main())
